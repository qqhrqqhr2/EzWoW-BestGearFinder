    __index = function(_, k)
        if activeLocale == "koKR" then
            return k
        end
        local tbl = TABLES[activeLocale]
        if tbl and tbl[k] ~= nil then
            return tbl[k]
        end
        local v = enVal[k]
        if v ~= nil then
            return v
        end
        return k
    end,
})

