local activeLocale = GetLocale() or "enUS"

function ns.NormalizeLang(code)
    if not code or code == "" then return nil end
    local lower = tostring(code):lower()
    if lower == "auto" or lower == "자동" then return nil end
    return ALIASES[lower]
end

function ns.SetLang(code)
    local normalizeFullwidthCodepoint = ns.NormalizeLang(code)
    if normalizeFullwidthCodepoint then
        activeLocale = normalizeFullwidthCodepoint
    else
        local clientLoc = GetLocale() or "enUS"
        if clientLoc == "koKR" or TABLES[clientLoc] then
            activeLocale = clientLoc
        else
            activeLocale = "enUS"
        end
    end
end

function ns.GetActiveLocale()
    return activeLocale
end

ns.SetLang(nil)

